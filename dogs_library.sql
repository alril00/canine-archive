-- 1. Таблица кинологических групп пород
CREATE TABLE IF NOT EXISTS groups (
    id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    origin_country VARCHAR(150) NOT NULL,
    image_path VARCHAR(255) NOT NULL,
    short_desc TEXT NOT NULL,
    notes TEXT,
    content TEXT NOT NULL
);

-- 2. Таблица пород собак (связь 1:N с таблицей groups через group_id)
CREATE TABLE IF NOT EXISTS breeds (
    id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    group_id VARCHAR(50) NOT NULL,
    origin VARCHAR(150) NOT NULL,
    height VARCHAR(50) NOT NULL,
    weight VARCHAR(50) NOT NULL,
    lifespan VARCHAR(50) NOT NULL,
    coat_type VARCHAR(255) NOT NULL,
    shedding_text VARCHAR(100) NOT NULL,
    shedding_level INT NOT NULL CHECK (shedding_level BETWEEN 1 AND 5),
    intelligence INT NOT NULL CHECK (intelligence BETWEEN 1 AND 5),
    energy INT NOT NULL CHECK (energy BETWEEN 1 AND 5),
    friendliness INT NOT NULL CHECK (friendliness BETWEEN 1 AND 5),
    trainability INT NOT NULL CHECK (trainability BETWEEN 1 AND 5),
    sound_desc VARCHAR(255),
    video_hint VARCHAR(255),
    description TEXT NOT NULL,
    history TEXT NOT NULL,
    health TEXT NOT NULL,
    notes TEXT,
    FOREIGN KEY (group_id) REFERENCES groups(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- 3. Таблица изображений для фотогалереи пород (связь 1:N с таблицей breeds)
CREATE TABLE IF NOT EXISTS breed_images (
